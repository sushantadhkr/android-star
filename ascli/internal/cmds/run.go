// GeneratedPath is where the generated command table lives.
//
// Found by walking up rather than assumed to be relative to the working directory, because the
// generator runs from the module root, `go test` runs from the package directory, and a hard-coded
// relative path silently found nothing in both.
func GeneratedPath() string {
	relative := filepath.Join("internal", "cmds", "commands_gen.go")

	dir, err := os.Getwd()
	if err != nil {
		return relative
	}
	for {
		candidate := filepath.Join(dir, relative)
		if _, err := os.Stat(candidate); err == nil {
			return candidate
		}
		parent := filepath.Dir(dir)
		if parent == dir {
			return relative
		}
		dir = parent
	}
}

// GeneratedCommand is one command, as generated from the platform's docs.
type GeneratedCommand struct {
	// Capability is the platform's own id, sent verbatim.
	Capability string
	Action     string
	// Path is the command as a human types it: "camera capture".
	Path string
	// Summary is the platform's own one-liner, not a paraphrase.
	Summary string
	// Params are the documented request fields, in order.
	Params []client.DocParam
}

// ParamNames lists the flags, for the drift check.
func (g GeneratedCommand) ParamNames() []string {
	names := make([]string, 0, len(g.Params))
	for _, p := range g.Params {
		names = append(names, p.Name)
	}
	return names
}

// Render produces the generated Go source from a docs payload.
//
// Generated rather than hand-written for one reason: a CLI covering every action the platform has
// can only stay correct if nobody types them out. Everything below is derived from what the
// platform says about itself.
func Render(docs *client.Docs) (string, error) {
	if docs == nil || len(docs.Capabilities) == 0 {
		return "", fmt.Errorf("the docs payload has no capabilities in it")
	}

	commands := CommandsFrom(docs)

	var b strings.Builder
	b.WriteString("// Code generated by `make generate`. DO NOT EDIT.\n")
	b.WriteString("//\n")
	b.WriteString("// Built from the platform's own /api/capabilities/docs. To change what is in here,\n")
	b.WriteString("// change the platform and run `make generate` — editing this file directly is how\n")
	b.WriteString("// the CLI and the API stop agreeing without anyone noticing.\n\n")
	b.WriteString("package cmds\n\n")
	b.WriteString("import \"github.com/sushantadhkr/android-star/ascli/internal/client\"\n\n")
	b.WriteString("// generatedCommands is every action the platform documents, in the platform's order.\n")
	b.WriteString("var generatedCommands = []GeneratedCommand{\n")

	for _, cmd := range commands {
		b.WriteString("\t{\n")
		fmt.Fprintf(&b, "\t\tCapability: %q,\n", cmd.Capability)
		fmt.Fprintf(&b, "\t\tAction: %q,\n", cmd.Action)
		fmt.Fprintf(&b, "\t\tPath: %q,\n", cmd.Path)
		fmt.Fprintf(&b, "\t\tSummary: %q,\n", cmd.Summary)
		if len(cmd.Params) > 0 {
			b.WriteString("\t\tParams: []client.DocParam{\n")
			for _, p := range cmd.Params {
				b.WriteString("\t\t\t{Name: ")
				fmt.Fprintf(&b, "%q, Type: %q, Required: %t, Description: %q", p.Name, p.Type, p.Required, p.Description)
				if p.Example != "" {
					fmt.Fprintf(&b, ", Example: %q", p.Example)
				}
				b.WriteString("},\n")
			}
			b.WriteString("\t\t},\n")
		}
		b.WriteString("\t},\n")
	}

	b.WriteString("}\n")

	// Formatted before it is returned, so `gofmt` has nothing to change and the drift check does
	// not fail simply because the generator's idea of layout differs from the toolchain's. Without
	// this, `make check` and `gofmt -w` undo each other on every run.
	formatted, err := format.Source([]byte(b.String()))
	if err != nil {
		return "", fmt.Errorf("the generated commands did not parse: %w", err)
	}
	return string(formatted), nil
}

// CommandsFrom flattens a docs payload into commands, dropping the ones with no name to type.
func CommandsFrom(docs *client.Docs) []GeneratedCommand {
	var commands []GeneratedCommand
	for _, capability := range docs.Capabilities {
		for _, action := range capability.Actions {
			if action.Name == "" {
				continue
			}
			commands = append(commands, GeneratedCommand{
				Capability: capability.ID,
				Action:     action.Name,
				Path:       CommandName(capability.ID) + " " + CommandName(action.Name),
				Summary:    action.Summary,
				Params:     action.Params,
			})
		}
	}
	return commands
}

// GeneratedCommands returns the table compiled into this binary.
func GeneratedCommands() []GeneratedCommand { return generatedCommands }

// FindCommand looks a typed command up by its path.
func FindCommand(path string) (GeneratedCommand, bool) {
	for _, cmd := range generatedCommands {
		if cmd.Path == path {
			return cmd, true
		}
	}
	return GeneratedCommand{}, false
}

// Run executes a generated command.
//
// `flags` are the values the caller supplied, keyed by the platform's own parameter name rather
// than by the CLI's spelling, so what is sent is what the platform documented.
// resolveParam maps a flag as typed to the parameter name the platform documents.
//
// Both spellings are accepted: the platform's own (`--maxWidth`, which is what its docs and
// examples use, and what `--help` shows) and the dashed form a shell reads more comfortably
// (`--max-width`). The platform's spelling wins when both could apply, and neither is guessed at
// when nothing matches — an unrecognised flag is reported rather than forwarded, because
// forwarding it turns a typo into a confusing refusal from the other end.
func resolveParam(supplied string, known []client.DocParam) (string, bool) {
	for _, param := range known {
		if param.Name == supplied {
			return param.Name, true
		}
	}
	for _, param := range known {
		if strings.EqualFold(param.Name, supplied) {
			return param.Name, true
		}
	}
	// Separators dropped before comparing, so max-width, max_width and maxwidth all find maxWidth.
	// The platform spells its parameters in camel case with no separators; shells and people reach
	// for both kinds of dash, and refusing a spelling over punctuation is not useful strictness.
	normalised := stripSeparators(strings.ToLower(supplied))
	for _, param := range known {
		if stripSeparators(strings.ToLower(param.Name)) == normalised {
			return param.Name, true
		}
	}
	return "", false
}

func stripSeparators(s string) string {
	return strings.NewReplacer("-", "", "_", "").Replace(s)
}

// Run executes a generated command.
//
// `flags` are keyed by whatever the caller typed; they are resolved to the platform's own
// parameter names here, so what is sent is what the platform documented.
func Run(ctx context.Context, c *client.Client, o *Output, cmd GeneratedCommand, flags map[string]string) error {
	raw, err := InvokeGenerated(ctx, c, cmd, flags)
	if err != nil {
		return err
	}
	return o.Result(raw)
}

// InvokeGenerated validates and runs a generated command, returning the platform's reply unprinted.
//
// Split from [Run] so the `-o` path can run an action, read the id out of what it said, and then
// fetch the file — without printing a receipt for a command the user asked to produce a file.
func InvokeGenerated(ctx context.Context, c *client.Client, cmd GeneratedCommand, flags map[string]string) ([]byte, error) {
	params := map[string]any{}

	// Resolve every supplied flag first, so a typo is reported before anything is sent.
	resolved := map[string]string{}
	for name, value := range flags {
		if name == "watch" || name == "until" || name == "output" || name == "out" {
			// Client-side flags, not the platform's.
			continue
		}
		paramName, ok := resolveParam(name, cmd.Params)
		if !ok {
			// Not in the generated table — most likely an action newer than this build. Passed
			// through untouched so an out-of-date CLI still works.
			resolved[name] = value
			continue
		}
		resolved[paramName] = value
	}

	known := map[string]client.DocParam{}
	for _, p := range cmd.Params {
		known[p.Name] = p
	}

	for name, value := range resolved {
		doc, ok := known[name]
		if !ok {
			// Not a parameter this command documents. Sent as typed: this path exists so an action
			// newer than this build is still reachable, and the platform is the authority on what
			// it takes.
			params[name] = value
			continue
		}
		converted, err := coerce(value, doc.Type)
		if err != nil {
			return nil, &client.Error{
				Status:  400,
				Message: fmt.Sprintf("--%s: %s", name, err.Error()),
				Hint:    doc.Description,
			}
		}
		params[name] = converted
	}

	// A required parameter missing is caught here, where the help can be shown, rather than at the
	// platform as a 400.
	for _, p := range cmd.Params {
		if p.Required {
			if _, ok := params[p.Name]; !ok {
				hint := p.Description
				if p.Example != "" {
					hint += fmt.Sprintf("  e.g. --%s %s", p.Name, p.Example)
				}
				return nil, &client.Error{
					Status:  400,
					Message: fmt.Sprintf("'%s' needs --%s.", cmd.Path, p.Name),
					Hint:    hint,
				}
			}
		}
	}

	return c.Invoke(ctx, cmd.Capability, cmd.Action, params)
}

// IDFrom pulls the id out of an action's reply, so `-o` knows what to fetch.
//
// Looks for the conventional fields rather than insisting on one, because the platform does not
// promise a single shape: a capture says "id", and anything that names something it made is fair
// game. If nothing looks like an id, that is said plainly instead of fetching nothing and calling it
// a success.
func IDFrom(raw []byte) (string, error) {
	var payload map[string]any
	if err := json.Unmarshal(raw, &payload); err != nil {
		return "", &client.Error{
			Status:  500,
			Message: "The platform's reply could not be read.",
			Hint:    truncate(string(raw), 300),
		}
	}
	for _, key := range []string{"id", "downloadId", "captureId"} {
		if value, ok := payload[key].(string); ok && value != "" {
			return value, nil
		}
	}
	return "", &client.Error{
		Status:  500,
		Message: "That action did not report an id, so there is nothing to fetch.",
		Hint: fmt.Sprintf("It replied: %s\n"+
			"Fetch the file yourself with:  ascli pull <FEATURE> <id> -o <file>", truncate(string(raw), 200)),
	}
}

// Save pulls a file the platform produced and writes it where the caller asked.
//
// The whole point of the pull route. `-o -` streams to stdout so the output can go straight into
// something else; a path writes to disk and says where. Nothing is written to a temporary file
// first, because a photo is small and a failed transfer should not leave a truncated file that
// looks like the real one.
func Save(ctx context.Context, c *client.Client, o *Output, capability, id, destination string) error {
	if id == "" {
		return &client.Error{
			Status:  400,
			Message: "No id to pull.",
			Hint:    "Run the action that produces the file first — capture returns an id.",
		}
	}

	if destination == "-" {
		written, name, err := c.Pull(ctx, capability, id, o.Out)
		if err != nil {
			return err
		}
		if !o.JSON && name != "" {
			fmt.Fprintf(o.Err, "\n  %s · %s → stdout\n", name, humanBytes(written))
		}
		return nil
	}

	file, err := os.Create(destination)
	if err != nil {
		return fmt.Errorf("cannot write %s: %w", destination, err)
	}

	written, name, err := c.Pull(ctx, capability, id, file)
	closeErr := file.Close()
	if err != nil {
		// A partial file is removed rather than left behind: something named shot.jpg that is
		// half a photo is worse than nothing, because it looks like a result.
		_ = os.Remove(destination)
		return err
	}
	if closeErr != nil {
		_ = os.Remove(destination)
		return fmt.Errorf("cannot finish writing %s: %w", destination, closeErr)
	}

	if !o.JSON {
		label := name
		if label == "" {
			label = filepath.Base(destination)
		}
		fmt.Fprintf(o.Out, "  %s · %s → %s\n", label, humanBytes(written), destination)
	}
	return nil
}

func humanBytes(n int64) string {
	switch {
	case n >= 1_000_000_000:
		return fmt.Sprintf("%.1f GB", float64(n)/1_000_000_000)
	case n >= 1_000_000:
		return fmt.Sprintf("%.1f MB", float64(n)/1_000_000)
	case n >= 1_000:
		return fmt.Sprintf("%.0f kB", float64(n)/1_000)
	default:
		return fmt.Sprintf("%d B", n)
	}
}

// Invoke runs anything by name, for the cases the generated table does not cover — an action added
// to the platform since this CLI was built, or one reached through a shortcut route.
func Invoke(ctx context.Context, c *client.Client, o *Output, capability, action string, flags map[string]string) error {
	raw, err := invokeTyped(ctx, c, capability, action, flags)
	if err != nil {
		return err
	}
	return o.Result(raw)
}

// Watch polls an action until it reaches one of `settled`, printing only when the state changes.
//
// The one piece of sugar the generated commands do not have, and it earns its place: a download
// that takes fifteen seconds should not need a hand-written shell loop every time.
//
// Only states that differ from last poll are printed, so the output is the changes rather than
// forty identical lines.
func Watch(ctx context.Context, c *client.Client, o *Output, capability, action string, flags map[string]string, settled []string) error {
	last := ""
	interval := time.Second

	for {
		raw, err := invokeTyped(ctx, c, capability, action, flags)
		if err != nil {
			return err
		}

		var payload map[string]any
		_ = json.Unmarshal(raw, &payload)
		state := firstString(payload, "status", "state")
		if state == "" {
			state = strings.TrimSpace(string(raw))
		}

		if state != last {
			if o.JSON {
				_ = pretty(raw, o.Out)
			} else {
				fmt.Fprintf(o.Out, "  %s\n", state)
			}
			last = state
		}

		for _, terminal := range settled {
			if strings.EqualFold(state, terminal) {
				// A finished-but-unsuccessful watch is a failure, not a quiet success.
				if isUnsuccessful(state) {
					return errSilent
				}
				return nil
			}
		}

		select {
		case <-ctx.Done():
			return fmt.Errorf("stopped watching before it finished (last state: %s)", last)
		case <-time.After(interval):
		}
	}
}

func isUnsuccessful(state string) bool {
	switch strings.ToLower(state) {
	case "failed", "cancelled", "canceled", "error":
		return true
	}
	return false
}

// invokeTyped sends an action with its parameters converted to the types the platform documents.
//
// Shared by [Invoke] and [Watch] so a watched action and a run one are typed identically — a
// divergence there would mean a poll sending "42" where the first call sent 42.
func invokeTyped(ctx context.Context, c *client.Client, capability, action string, flags map[string]string) ([]byte, error) {
	if len(flags) == 0 {
		return c.Invoke(ctx, capability, action, nil)
	}

	docTypes := map[string]string{}
	if docs, err := c.Docs(ctx); err == nil {
		for _, capabilityDoc := range docs.Capabilities {
			if !strings.EqualFold(capabilityDoc.ID, capability) {
				continue
			}
			for _, actionDoc := range capabilityDoc.Actions {
				if !strings.EqualFold(actionDoc.Name, action) {
					continue
				}
				for _, p := range actionDoc.Params {
					docTypes[p.Name] = p.Type
				}
			}
		}
	}

	params := map[string]any{}
	for name, value := range flags {
		docType, known := docTypes[name]
		if !known {
			// The docs did not describe this parameter. Either the action is newer than the
			// platform we asked, or the platform could not be reached. Either way the name is put
			// into the platform's own convention — dashes become camel case — because that is how
			// every parameter it has ever documented is spelled. Sending `max-width` to a platform
			// whose field is `maxWidth` would be refused for a reason the user cannot act on.
			params[camelCase(name)] = value
			continue
		}
		converted, err := coerce(value, docType)
		if err != nil {
			return nil, &client.Error{
				Status:  400,
				Message: fmt.Sprintf("--%s: %s", name, err.Error()),
			}
		}
		params[name] = converted
	}
	return c.Invoke(ctx, capability, action, params)
}

// camelCase turns max-width into maxWidth, and leaves anything already camel cased alone.
func camelCase(name string) string {
	parts := strings.Split(name, "-")
	for i := 1; i < len(parts); i++ {
		if parts[i] == "" {
			continue
		}
		parts[i] = strings.ToUpper(parts[i][:1]) + parts[i][1:]
	}
	return strings.Join(parts, "")
}

func firstString(m map[string]any, keys ...string) string {
	for _, key := range keys {
		if value, ok := m[key].(string); ok {
			return value
		}
	}
	return ""
}
