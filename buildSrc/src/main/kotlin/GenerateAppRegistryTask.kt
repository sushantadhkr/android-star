import org.gradle.api.DefaultTask
import org.gradle.api.file.ConfigurableFileCollection
import org.gradle.api.file.DirectoryProperty
import org.gradle.api.tasks.InputFiles
import org.gradle.api.tasks.OutputDirectory
import org.gradle.api.tasks.TaskAction
import java.io.File
import java.util.Locale

/** One App discovered in the sources. */
data class DiscoveredApp(
    val packageName: String,
    val className: String,
    val appId: String,
    val appName: String,
    val order: Int
)

/**
 * Generates the App registry from `@PlatformAppDefinition` declarations.
 *
 * Adding an App therefore never requires hand-editing the shell: annotate the App, rebuild, and it
 * appears on the Apps page with its toggle. The generated file is a build artifact and is never
 * committed.
 *
 * The scan is deliberately simple — it reads the annotation's identity, display name and ordering,
 * and takes richer metadata from the App instance itself.
 */
abstract class GenerateAppRegistryTask : DefaultTask() {

    @get:InputFiles
    abstract val sourceDirs: ConfigurableFileCollection

    @get:OutputDirectory
    abstract val outputDirectory: DirectoryProperty

    @TaskAction
    fun generate() {
        val target = outputDirectory.get().asFile
        target.deleteRecursively()
        target.mkdirs()

        val discovered = discoverApps(sourceDirs.files.toList())
        target.resolve("GeneratedAppRegistry.kt").writeText(renderRegistry(discovered))
        logger.lifecycle("generateAppRegistry: discovered ${discovered.size} App(s)")
    }

    private fun discoverApps(sourceDirs: List<File>): List<DiscoveredApp> {
        val annotationPattern = Regex("@PlatformAppDefinition\\s*\\(([^)]*)\\)")
        val classPattern = Regex("class\\s+(\\w+)")
        val found = mutableListOf<DiscoveredApp>()

        sourceDirs.filter { it.exists() }.forEach { dir ->
            dir.walkTopDown()
                .filter { it.isFile && it.extension.lowercase(Locale.ROOT) == "kt" }
                .forEach { file ->
                    val text = file.readText()
                    if (!text.contains("@PlatformAppDefinition")) return@forEach

                    val packageName = Regex("^package\\s+([\\w.]+)", RegexOption.MULTILINE)
                        .find(text)?.groupValues?.get(1).orEmpty()

                    annotationPattern.findAll(text).forEach { annotationMatch ->
                        // The annotated class is the first class declared after the annotation.
                        val remainder = text.substring(annotationMatch.range.last + 1)
                        val className = classPattern.find(remainder)?.groupValues?.get(1)
                            ?: return@forEach
                        val args = annotationMatch.groupValues[1]

                        found += DiscoveredApp(
                            packageName = packageName,
                            className = className,
                            appId = Regex("id\\s*=\\s*\"([^\"]*)\"")
                                .find(args)?.groupValues?.get(1) ?: className,
                            appName = Regex("name\\s*=\\s*\"([^\"]*)\"")
                                .find(args)?.groupValues?.get(1) ?: className,
                            order = Regex("order\\s*=\\s*(\\d+)")
                                .find(args)?.groupValues?.get(1)?.toIntOrNull() ?: 100
                        )
                    }
                }
        }

        return found.sortedBy { it.order }
    }

    private fun renderRegistry(discovered: List<DiscoveredApp>): String = buildString {
        appendLine("// GENERATED BY THE BUILD - do not edit, do not commit.")
        appendLine("// Produced by generateAppRegistry from @PlatformAppDefinition declarations.")
        appendLine("@file:Suppress(\"UNUSED_PARAMETER\")")
        appendLine()
        appendLine("package com.personal.base.generated")
        appendLine()
        appendLine("import com.personal.base.core.app.AppRegistration")
        appendLine("import com.personal.base.core.capability.CapabilityType")
        discovered.forEach { appendLine("import ${it.packageName}.${it.className}") }
        appendLine()
        appendLine("/**")
        appendLine(" * Every App declared in this build, in declared order.")
        appendLine(" *")
        appendLine(" * Generated - do not edit. Apps are added by annotating them, never by editing")
        appendLine(" * this file.")
        appendLine(" */")
        appendLine("object GeneratedAppRegistry {")
        appendLine("    val registrations: List<AppRegistration> = listOf(")
        discovered.forEach { app ->
            appendLine("        AppRegistration(")
            appendLine("            id = \"${app.appId}\",")
            appendLine("            name = \"${app.appName}\",")
            appendLine("            description = \"\",")
            appendLine("            version = \"1.0\",")
            appendLine("            icon = ${app.className}().icon,")
            appendLine("            category = \"Tools\",")
            appendLine("            requiredCapabilities = emptySet<CapabilityType>(),")
            appendLine("            order = ${app.order},")
            appendLine("            factory = { ${app.className}() }")
            appendLine("        ),")
        }
        appendLine("    )")
        appendLine("}")
    }
}